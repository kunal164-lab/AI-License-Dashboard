// ---- Microsoft 365 dedicated-page "Complete Report" — a management-
// friendly summary across every synced dataset (Users/Devices/Applications/
// Licenses/Departments/Groups/Sign-ins/Copilot), reusing the same shared
// header/section/table/footer helpers every other report in this file
// already uses. Not a general per-record dataset dump (that's what each
// view's own CSV/XLSX export in src/utils/datasetExport.js is for) — this
// is the one-page-per-tenant executive summary.
export async function buildMicrosoft365OverviewPdf(model) {
  const doc = new jsPDF()
  let y = await reportHeader(doc, model)

  y = sectionHeading(doc, 'Microsoft 365 Summary', y)
  autoTable(doc, {
    startY: y, margin: AUTO_TABLE_MARGIN, styles: { fontSize: 10 }, columnStyles: { 0: { fontStyle: 'bold', cellWidth: 70 } },
    body: [
      ['Users', model.counts.users], ['Devices', model.counts.devices],
      ['Applications', model.counts.applications], ['Assigned Licenses', model.counts.licenses],
      ['Groups', model.counts.groups], ['Teams', model.counts.teams],
      ['Copilot Users', model.counts.copilotUsers],
      ['Copilot License Active', model.counts.copilotLicenseActive],
      ['Sign-ins (synced period)', model.counts.signIns]
    ]
  })
  y = doc.lastAutoTable.finalY + 10

  if (model.departments.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Users by Department', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['Department', 'Users']], body: model.departments.map((d) => [na(d.department), d.count])
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (model.domains.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Domain Comparison', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['Domain', 'Total Users', 'Active Users']], body: model.domains.map((d) => [na(d.domain), d.totalUsers, d.activeUsers])
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (model.licenses.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'License Assignment', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['License (SKU)', 'Assigned Users']], body: model.licenses.map((l) => [na(l.sku), l.count])
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (model.applications?.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Top Applications', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['Application', 'Publisher', 'Installations']],
      body: model.applications.map((a) => [na(a.display_name), na(a.publisher), a.device_count?.toLocaleString?.() ?? na(a.device_count)])
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (model.groupsByType?.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Groups & Teams', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['Type', 'Count']], body: model.groupsByType.map((g) => [na(g.name), g.value])
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (model.signInsByDay?.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Sign-ins by Day', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['Day', 'Successful', 'Failed']], body: model.signInsByDay.slice(-15).map((d) => [na(d.day), d.success, d.failure])
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (model.copilotBreakdown?.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Copilot — License Status vs Usage Status', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['License Status', 'Usage Status', 'Users']],
      body: model.copilotBreakdown.map((c) => [na(c.licenseStatus), na(c.usageStatus), c.count])
    })
  }

  drawFooterOnAllPages(doc, model.generatedAt)
  return doc
}

