// ---- Microsoft 365 User Detail export (different shape again — reuses
// reportHeader by conforming to its generic title/generatedAt/scope/etc.
// fields; see src/utils/microsoftReportModels.js for how the model is
// assembled from the /api/microsoft/users/:id response) ----
export async function buildMicrosoftUserPdf(model) {
  const doc = new jsPDF()
  let y = await reportHeader(doc, model)
  const p = model.profile

  y = sectionHeading(doc, 'Profile', y)
  autoTable(doc, {
    startY: y, margin: AUTO_TABLE_MARGIN, styles: { fontSize: 10 }, columnStyles: { 0: { fontStyle: 'bold', cellWidth: 60 } },
    body: [
      ['Display Name', na(p.display_name)], ['Email / UPN', na(p.upn)], ['User ID', na(p.ms_id)],
      ['Job Title', na(p.job_title)], ['Department', na(p.department)], ['Company', na(p.company_name)],
      ['Office', na(p.office_location)], ['Domain', na(p.domain)],
      ['Account Status', p.account_enabled ? 'Enabled' : 'Disabled'],
      ['Manager', na(p.manager_display_name)], ['VBU / Organization', na(p.vbu)]
    ]
  })
  y = doc.lastAutoTable.finalY + 10

  y = sectionHeading(doc, 'Assigned Microsoft 365 Licenses', y)
  if (model.licenses.length) {
    autoTable(doc, { startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 }, head: [['License (SKU)']], body: model.licenses.map((l) => [na(l.sku_part_number)]) })
    y = doc.lastAutoTable.finalY + 10
  } else {
    doc.setFontSize(9); doc.setTextColor(107, 114, 128); doc.text('No licenses assigned.', MARGIN, y); doc.setTextColor(0, 0, 0); y += 10
  }

  y = sectionHeading(doc, 'Copilot Usage', y)
  if (model.copilot) {
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, styles: { fontSize: 10 }, columnStyles: { 0: { fontStyle: 'bold', cellWidth: 60 } },
      body: [['Usage (Activity)', na(model.copilot.activity_count)], ['Last Active', na(model.copilot.last_activity)], ['Plan', na(model.copilot.plan)]]
    })
    y = doc.lastAutoTable.finalY + 10
  } else {
    doc.setFontSize(9); doc.setTextColor(107, 114, 128); doc.text('No Copilot usage data available for this user.', MARGIN, y); doc.setTextColor(0, 0, 0); y += 10
  }

  y = ensureSpace(doc, y, 20)
  y = sectionHeading(doc, 'Devices', y)
  if (model.devices.length) {
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 8 },
      head: [['Device', 'OS', 'Compliance', 'Management', 'Last Sync']],
      body: model.devices.map((d) => [na(d.device_name), na(d.operating_system), na(d.compliance_state), na(d.management_state), fmtDate(d.last_sync_at)])
    })
    y = doc.lastAutoTable.finalY + 10
  } else {
    doc.setFontSize(9); doc.setTextColor(107, 114, 128); doc.text('No devices assigned to this user.', MARGIN, y); doc.setTextColor(0, 0, 0); y += 10
  }

  y = ensureSpace(doc, y, 20)
  y = sectionHeading(doc, 'Applications', y)
  if (model.applications.length) {
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 8 },
      head: [['Application', 'Version', 'Device(s)']],
      body: model.applications.map((a) => [na(a.display_name), na(a.version), (a.devices || []).join(', ') || 'N/A'])
    })
    y = doc.lastAutoTable.finalY + 10
  } else {
    doc.setFontSize(9); doc.setTextColor(107, 114, 128)
    doc.text(model.applicationsError ? `Application data unavailable: ${model.applicationsError}` : 'No application data available for this user\'s devices.', MARGIN, y)
    doc.setTextColor(0, 0, 0); y += 10
  }

  if (model.signIns.length) {
    y = ensureSpace(doc, y, 20)
    y = sectionHeading(doc, 'Recent Sign-in Activity', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 8 },
      head: [['Time', 'Application', 'Status']],
      body: model.signIns.slice(0, 20).map((s) => [fmtDate(s.created_at), na(s.app_display_name), na(s.status)])
    })
  }

  drawFooterOnAllPages(doc, model.generatedAt)
  return doc
}

