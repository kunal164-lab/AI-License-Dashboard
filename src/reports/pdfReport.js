import { getLogoDataUrl, LOGO_ASPECT_RATIO } from './logo.js'

const BRAND_BLUE = [11, 95, 255]
const MARGIN = 14
const PAGE_WIDTH = 210 // A4 mm

// Reserved at the bottom of every page for the footer (rule + disclaimer +
// generated/brand/page-number row) — ensureSpace() and every autoTable call
// below respect this so body content and tables never render into it, and
// a table that spans multiple pages breaks cleanly above the footer rather
// than under it.
const FOOTER_RESERVED_HEIGHT = 32
const AUTO_TABLE_MARGIN = { left: MARGIN, right: MARGIN, bottom: FOOTER_RESERVED_HEIGHT }
const DISCLAIMER_TEXT = 'Disclaimer: This report is automatically generated by the Internal IT Dashboard for internal informational and reporting purposes. Data is based on the latest successfully retrieved or imported source data available at the time of report generation. Please verify critical information with the respective source system before making business or licensing decisions.'

function money(v) { return v === null || v === undefined ? 'N/A' : '$' + Number(v).toLocaleString(undefined, { maximumFractionDigits: 2 }) }
function pct(v) { return v === null || v === undefined ? 'N/A' : v + '%' }
function na(v) { return v === null || v === undefined || v === '' ? 'N/A' : v }
function fmtDate(iso) { return iso ? new Date(iso).toLocaleString() : 'N/A' }

function ensureSpace(doc, y, needed) {
  const pageHeight = doc.internal.pageSize.getHeight()
  if (y + needed > pageHeight - FOOTER_RESERVED_HEIGHT) {
    doc.addPage()
    return 20
  }
  return y
}

function sectionHeading(doc, text, y) {
  y = ensureSpace(doc, y, 14)
  doc.setFontSize(12)
  doc.setTextColor(17, 24, 39)
  doc.setFont(undefined, 'bold')
  doc.text(text, MARGIN, y)
  doc.setFont(undefined, 'normal')
  return y + 6
}

function breakdownTable(doc, title, rows, nameLabel, y, extraCol) {
  if (!rows.length) return y
  y = sectionHeading(doc, title, y)
  const head = [[nameLabel, 'Users', 'Licenses', 'Active', 'Utilization', 'Spend', 'Usage', ...(extraCol ? [extraCol] : [])]]
  const body = rows.map((r) => [
    r.name, r.users, r.licenses, r.activeLicenses, pct(r.utilization), money(r.spend), r.usage.toLocaleString(),
    ...(extraCol ? [money(r.potentialSavings)] : [])
  ])
  autoTable(doc, { startY: y, head, body, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 } })
  return doc.lastAutoTable.finalY + 10
}

// Draws the branded masthead (logo + "Internal IT Dashboard" + report
// title) at the top of the CURRENT page. Async because the logo (the
// existing public/ssp-logo.png asset — never a new/fake image) is fetched
// and base64-encoded on first use; if that fails for any reason, the
// header still renders correctly with text only — a missing logo must
// never break report generation.
async function reportHeader(doc, model) {
  doc.setFillColor(...BRAND_BLUE)
  doc.rect(0, 0, PAGE_WIDTH, 22, 'F')

  let textX = MARGIN
  const logoDataUrl = await getLogoDataUrl()
  if (logoDataUrl) {
    try {
      const logoHeight = 14
      const logoWidth = logoHeight * LOGO_ASPECT_RATIO
      doc.addImage(logoDataUrl, 'PNG', MARGIN, 4, logoWidth, logoHeight)
      textX = MARGIN + logoWidth + 5
    } catch (e) {
      textX = MARGIN // corrupt/unsupported image data — fall back to text-only header
    }
  }

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(9)
  doc.setFont(undefined, 'bold')
  doc.text('Internal IT Dashboard', textX, 10)
  doc.setFont(undefined, 'normal')
  doc.setFontSize(16)
  doc.text(model.title, textX, 18)

  let y = 30
  doc.setTextColor(55, 65, 81)
  doc.setFontSize(9)
  doc.text(`Generated: ${fmtDate(model.generatedAt)}`, MARGIN, y)
  doc.text(`Data last updated: ${fmtDate(model.dataLastUpdated)}`, MARGIN, y + 5)
  doc.text(`Scope: ${model.scope === 'filtered' ? 'Filtered dataset' : 'Complete dataset'} (${model.recordCount.toLocaleString()} records)`, MARGIN, y + 10)
  y += 15

  if (model.sources && model.sources.length) {
    doc.text(`Sources: ${model.sources.map((s) => s.label).join(', ')}`, MARGIN, y)
    y += 5
  }
  if (model.scope === 'filtered' && model.filtersApplied.length) {
    doc.setFont(undefined, 'bold')
    doc.text('Filters Applied:', MARGIN, y)
    doc.setFont(undefined, 'normal')
    y += 5
    model.filtersApplied.forEach((f) => { doc.text(`- ${f}`, MARGIN + 2, y); y += 5 })
  }
  return y + 4
}

// Drawn once, after every page of content already exists, so the total
// page count is known upfront for "Page X of Y" — looping back over every
// page with doc.setPage() rather than trying to draw it page-by-page while
// content is still being added.
function drawFooterOnAllPages(doc, generatedAt) {
  const pageCount = doc.internal.getNumberOfPages()
  const pageHeight = doc.internal.pageSize.getHeight()
  const pageWidth = doc.internal.pageSize.getWidth()
  const footerTop = pageHeight - FOOTER_RESERVED_HEIGHT

  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)

    doc.setDrawColor(226, 232, 240)
    doc.setLineWidth(0.2)
    doc.line(MARGIN, footerTop, pageWidth - MARGIN, footerTop)

    doc.setFont(undefined, 'normal')
    doc.setFontSize(6.5)
    doc.setTextColor(107, 114, 128)
    const wrapped = doc.splitTextToSize(DISCLAIMER_TEXT, pageWidth - MARGIN * 2)
    doc.text(wrapped, MARGIN, footerTop + 4)

    doc.setFontSize(7.5)
    doc.setTextColor(75, 85, 99)
    doc.text(`Generated on: ${fmtDate(generatedAt)}`, MARGIN, pageHeight - 6)
    doc.text('Internal IT Dashboard', pageWidth / 2, pageHeight - 6, { align: 'center' })
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - MARGIN, pageHeight - 6, { align: 'right' })
  }
}

async function executiveSummaryTable(doc, model, y) {
  y = sectionHeading(doc, 'Executive Summary', y)
  const s = model.executiveSummary
  const body = [
    ['Total Users', s.totalUsers], ['Total Licenses', s.totalLicenses],
    ['Active Licenses', s.activeLicenses], ['License Utilization', pct(s.utilization)],
    ['Total Spend', money(s.totalSpend)], ['Potential Savings', money(s.potentialSavings)],
    ['Unused Licenses', s.unusedLicenses], ['Connected Sources', na(s.connectedSources)],
    // Cost report-only field (src/reports/reportBuilder.js's
    // buildCostReportModel) — absent from every other report's model, so
    // this row simply doesn't appear there.
    ...(model.lowUsageCost !== undefined ? [['Low-Usage License Cost', money(model.lowUsageCost)]] : [])
  ]
  autoTable(doc, { startY: y, body, margin: AUTO_TABLE_MARGIN, styles: { fontSize: 10 }, columnStyles: { 0: { fontStyle: 'bold', cellWidth: 60 } } })
  return doc.lastAutoTable.finalY + 10
}

function userAnalysisTables(doc, model, y) {
  const { topUsers, lowUsage } = model.userAnalysis
  if (topUsers.length) {
    y = sectionHeading(doc, 'Top Users by Usage', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['User', 'Product', 'Usage', 'Spend']],
      body: topUsers.map((u) => [u.name, na(u.product), na(u.activity_count), money(u.display_cost ?? null)])
    })
    y = doc.lastAutoTable.finalY + 10
  }
  if (lowUsage.length) {
    y = sectionHeading(doc, 'Low / No Usage Users', y)
    autoTable(doc, {
      startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
      head: [['User', 'Last Active', 'Product']],
      body: lowUsage.map((u) => [u.name, na(u.last_activity), na(u.product)])
    })
    y = doc.lastAutoTable.finalY + 10
  }
  return y
}

function activityTable(doc, model, y) {
  if (!model.activitySummary.length) return y
  y = sectionHeading(doc, 'AI Activity', y)
  autoTable(doc, {
    startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 9 },
    head: [['Metric', 'Total']],
    body: model.activitySummary.map((a) => [a.label, a.total.toLocaleString()])
  })
  return doc.lastAutoTable.finalY + 10
}

export async function buildReportPdf(model) {
  const doc = new jsPDF()
  let y = await reportHeader(doc, model)
  y = await executiveSummaryTable(doc, model, y)
  y = breakdownTable(doc, 'Provider Overview', model.providerBreakdown, 'Provider', y)
  y = breakdownTable(doc, 'Product Analysis', model.productBreakdown, 'Product', y, 'Potential Savings')
  y = breakdownTable(doc, 'Department Analysis', model.departmentBreakdown, 'Department', y)
  // VBU/domain/plan breakdowns only exist on the Cost report's model
  // (buildCostReportModel) — breakdownTable already no-ops on an empty
  // array, so this is a no-op for every other report.
  y = breakdownTable(doc, 'VBU Analysis', model.vbuBreakdown || [], 'VBU', y)
  y = breakdownTable(doc, 'Domain Analysis', model.domainBreakdown || [], 'Domain', y)
  y = breakdownTable(doc, 'License / Plan Analysis', model.planBreakdown || [], 'Plan', y, 'Potential Savings')
  y = userAnalysisTables(doc, model, y)
  activityTable(doc, model, y)
  drawFooterOnAllPages(doc, model.generatedAt)
  return doc
}

export async function downloadReportPdf(model, prefix = 'Internal_IT_Usage_Report') {
  const doc = await buildReportPdf(model)
  const filename = buildReportFilename({ prefix, scope: model.scope, filters: model.rawFilters, ext: 'pdf' })
  downloadBlob(doc.output('blob'), filename)
  return filename
}

