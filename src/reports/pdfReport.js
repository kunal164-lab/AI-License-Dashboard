// ---- Generic single-dataset PDF — the "Specific Reports" (Users/Devices/
// Applications/Licenses/Departments/Groups/Sign-ins/Copilot) in the
// Microsoft 365 page's unified export menu, and reused as-is (nothing here
// is Microsoft-specific) by any other page needing a scoped "dump these
// rows as a branded PDF table" export — e.g. Cost Analytics' By VBU view.
// One table dump reusing the exact same shared header/section/table/footer
// helpers as every other report above, rather than a bespoke report
// function per dataset — the columns/rows/title are all that differ.
export async function buildTabularDatasetPdf({ title, columns, rows, scope, filtersApplied, sources, generatedAt, dataLastUpdated }) {
  const doc = new jsPDF()
  const model = {
    title, generatedAt: generatedAt || new Date().toISOString(), dataLastUpdated: dataLastUpdated || null,
    scope: scope || 'complete', recordCount: rows.length, sources: sources || [{ label: 'Internal IT Dashboard' }], filtersApplied: filtersApplied || []
  }
  let y = await reportHeader(doc, model)
  y = sectionHeading(doc, `${title} (${rows.length.toLocaleString()})`, y)
  autoTable(doc, {
    startY: y, margin: AUTO_TABLE_MARGIN, headStyles: { fillColor: BRAND_BLUE }, styles: { fontSize: 7 },
    head: [columns.map((c) => c.label)],
    body: rows.map((r) => columns.map((c) => na(r[c.key])))
  })
  drawFooterOnAllPages(doc, model.generatedAt)
  return doc
}

export async function downloadTabularDatasetPdf(args) {
  const doc = await buildTabularDatasetPdf(args)
  const prefix = args.filePrefix || `Internal_IT_${args.title.replace(/[^a-zA-Z0-9]+/g, '_')}`
  const filename = buildReportFilename({ prefix, scope: args.scope || 'complete', filters: args.filtersApplied || [], ext: 'pdf' })
  downloadBlob(doc.output('blob'), filename)
  return filename
}
